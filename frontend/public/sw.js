/* CBE Life Scoreboard — Service Worker
 * Strategy:
 *  - App shell: stale-while-revalidate for navigations + static assets
 *  - Cache name versioning: bump CACHE_VERSION on deploy to invalidate old caches
 *  - All persistence is localStorage (in-page), so no API caching needed
 */

const CACHE_VERSION = "cbe-v1";
const APP_SHELL_CACHE = `${CACHE_VERSION}-shell`;
const RUNTIME_CACHE = `${CACHE_VERSION}-runtime`;

const APP_SHELL = [
  "/",
  "/index.html",
  "/manifest.json",
  "/icon.svg",
  "/icon-192.png",
  "/icon-512.png",
  "/apple-touch-icon.png",
  "/favicon.ico",
];

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches
      .open(APP_SHELL_CACHE)
      .then((cache) => cache.addAll(APP_SHELL))
      .then(() => self.skipWaiting())
      .catch(() => undefined),
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(
          keys
            .filter((k) => !k.startsWith(CACHE_VERSION))
            .map((k) => caches.delete(k)),
        ),
      )
      .then(() => self.clients.claim()),
  );
});

self.addEventListener("message", (event) => {
  if (event.data === "SKIP_WAITING") self.skipWaiting();
});

// Cache strategies
function isSameOrigin(url) {
  return url.origin === self.location.origin;
}

self.addEventListener("fetch", (event) => {
  const req = event.request;
  if (req.method !== "GET") return;

  const url = new URL(req.url);

  // Only handle same-origin (skip cross-origin like Google Fonts CDN, etc.)
  if (!isSameOrigin(url)) return;

  // Don't cache hot-reload websocket / sockjs / dev-only paths
  if (url.pathname.startsWith("/sockjs-node") || url.pathname.startsWith("/ws")) {
    return;
  }

  // Skip /api/* (this app has none, but future-proof)
  if (url.pathname.startsWith("/api")) {
    return;
  }

  // Navigation requests → network-first with offline fallback to cached index.html
  if (req.mode === "navigate") {
    event.respondWith(
      fetch(req)
        .then((res) => {
          const copy = res.clone();
          caches.open(RUNTIME_CACHE).then((c) => c.put(req, copy));
          return res;
        })
        .catch(() =>
          caches.match(req).then((m) => m || caches.match("/index.html")),
        ),
    );
    return;
  }

  // Static assets (JS/CSS/img/font) → stale-while-revalidate
  event.respondWith(
    caches.match(req).then((cached) => {
      const network = fetch(req)
        .then((res) => {
          if (res && res.status === 200 && res.type === "basic") {
            const copy = res.clone();
            caches.open(RUNTIME_CACHE).then((c) => c.put(req, copy));
          }
          return res;
        })
        .catch(() => cached);
      return cached || network;
    }),
  );
});
